-- ---------- Administradores ----------
create table if not exists public.admins (
  email text primary key,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.admins
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

-- ---------- Carta ----------
create table if not exists public.menu_categories (
  id     bigint generated by default as identity primary key,
  tab    text not null unique,
  note   text not null default '',
  sort   int  not null default 0,
  active boolean not null default true
);

create table if not exists public.menu_sections (
  id          bigint generated by default as identity primary key,
  category_id bigint not null references public.menu_categories(id) on delete cascade,
  title       text not null,
  sub         text not null default '',
  sort        int  not null default 0,
  active      boolean not null default true,
  unique (category_id, title)
);

create table if not exists public.menu_items (
  id           bigint generated by default as identity primary key,
  section_id   bigint not null references public.menu_sections(id) on delete cascade,
  name         text not null,
  price        numeric(10,2) check (price is null or price >= 0),          -- precio (o copa)
  bottle_price numeric(10,2) check (bottle_price is null or bottle_price >= 0), -- botella, si aplica
  label        text not null default '',     -- ej. "Próximamente" cuando no hay precio
  available    boolean not null default true, -- false = agotado
  sort         int  not null default 0,
  updated_at   timestamptz not null default now(),
  unique (section_id, name)
);

create index if not exists menu_sections_cat_idx on public.menu_sections(category_id, sort);
create index if not exists menu_items_sec_idx    on public.menu_items(section_id, sort);

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end; $$;

drop trigger if exists menu_items_touch on public.menu_items;
create trigger menu_items_touch before update on public.menu_items
for each row execute function public.touch_updated_at();

-- ---------- Promociones ----------
create table if not exists public.promos (
  id          bigint generated by default as identity primary key,
  label       text not null default '',   -- ej. "Jueves y viernes"
  title       text not null,
  description text not null default '',
  cta_text    text not null default '',   -- texto del botón (vacío = sin botón)
  cta_message text not null default '',   -- mensaje de WhatsApp del botón
  starts_on   date,
  ends_on     date,                        -- se oculta sola después de esta fecha
  active      boolean not null default true,
  sort        int not null default 0,
  created_at  timestamptz not null default now()
);

-- ---------- Pedidos ----------
create table if not exists public.orders (
  id         uuid primary key default gen_random_uuid(),
  folio      bigint generated by default as identity unique,
  created_at timestamptz not null default now(),
  items      jsonb not null,          -- [{item_id, name, variant, price, qty, subtotal}]
  total      numeric(10,2) not null,
  notes      text not null default '',
  status     text not null default 'nuevo'
             check (status in ('nuevo','confirmado','preparando','entregado','cancelado'))
);
create index if not exists orders_created_idx on public.orders(created_at desc);

-- Crea un pedido calculando los precios en el servidor (el cliente no decide el total).
-- p_items: [{"id": 12, "variant": "Botella" | null, "qty": 2}, ...]
create or replace function public.create_order(p_items jsonb, p_notes text default '')
returns table (folio bigint, total numeric)
language plpgsql security definer set search_path = public
as $$
declare
  r        jsonb;
  it       public.menu_items%rowtype;
  q        int;
  v        text;
  unit     numeric;
  lines    jsonb := '[]'::jsonb;
  t        numeric := 0;
  o_folio  bigint;
begin
  if p_items is null or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 60 then
    raise exception 'Pedido vacío o demasiado grande';
  end if;

  for r in select * from jsonb_array_elements(p_items) loop
    q := (r ->> 'qty')::int;
    if q is null or q < 1 or q > 50 then raise exception 'Cantidad inválida'; end if;

    select mi.* into it
    from public.menu_items mi
    join public.menu_sections s on s.id = mi.section_id and s.active
    join public.menu_categories c on c.id = s.category_id and c.active
    where mi.id = (r ->> 'id')::bigint and mi.available;
    if not found then raise exception 'Producto no disponible: %', r ->> 'id'; end if;

    v := nullif(r ->> 'variant', '');
    if v = 'Botella' then unit := it.bottle_price; else unit := it.price; end if;
    if unit is null then raise exception 'Producto sin precio: %', it.name; end if;

    t := t + unit * q;
    lines := lines || jsonb_build_object(
      'item_id', it.id, 'name', it.name, 'variant', v,
      'price', unit, 'qty', q, 'subtotal', unit * q);
  end loop;

  insert into public.orders (items, total, notes)
  values (lines, t, left(coalesce(p_notes, ''), 500))
  returning orders.folio into o_folio;

  return query select o_folio, t;
end; $$;

-- ---------- Seguridad (RLS) ----------
alter table public.admins          enable row level security;
alter table public.menu_categories enable row level security;
alter table public.menu_sections   enable row level security;
alter table public.menu_items      enable row level security;
alter table public.promos          enable row level security;
alter table public.orders          enable row level security;

-- Lectura pública de la carta y promos activas
drop policy if exists "public read categories" on public.menu_categories;
create policy "public read categories" on public.menu_categories for select using (active or public.is_admin());
drop policy if exists "public read sections" on public.menu_sections;
create policy "public read sections" on public.menu_sections for select using (active or public.is_admin());
drop policy if exists "public read items" on public.menu_items;
create policy "public read items" on public.menu_items for select using (true);
drop policy if exists "public read promos" on public.promos;
create policy "public read promos" on public.promos for select using (
  public.is_admin() or (active
    and (starts_on is null or starts_on <= (now() at time zone 'America/Mexico_City')::date)
    and (ends_on   is null or ends_on   >= (now() at time zone 'America/Mexico_City')::date)));

-- Escritura solo para administradores
drop policy if exists "admin write categories" on public.menu_categories;
create policy "admin write categories" on public.menu_categories for all using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admin write sections" on public.menu_sections;
create policy "admin write sections" on public.menu_sections for all using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admin write items" on public.menu_items;
create policy "admin write items" on public.menu_items for all using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admin write promos" on public.promos;
create policy "admin write promos" on public.promos for all using (public.is_admin()) with check (public.is_admin());

-- Pedidos: nadie los lee ni escribe directo salvo admins; el público usa create_order()
drop policy if exists "admin orders" on public.orders;
create policy "admin orders" on public.orders for all using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admin read admins" on public.admins;
create policy "admin read admins" on public.admins for select using (public.is_admin());

grant usage on schema public to anon, authenticated;
grant select on public.menu_categories, public.menu_sections, public.menu_items, public.promos to anon, authenticated;
grant insert, update, delete on public.menu_categories, public.menu_sections, public.menu_items, public.promos to authenticated;
grant select, update, delete on public.orders to authenticated;
grant select on public.admins to authenticated;
revoke all on function public.create_order(jsonb, text) from public;
grant execute on function public.create_order(jsonb, text) to anon, authenticated;
grant execute on function public.is_admin() to anon, authenticated;
